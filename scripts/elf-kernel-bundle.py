#!/usr/bin/env python3
"""Materialize libkrunfw's exact PT_LOAD kernel bundle without pyelftools."""

import argparse
import io
import math
import struct
import tarfile
from pathlib import Path
import sys


ELF64_HEADER = struct.Struct("<16sHHIQQQIHHHHHH")
ELF64_PROGRAM_HEADER = struct.Struct("<IIQQQQQQ")
PT_LOAD = 1
PAGE_SIZE = 65_536


def extract_debian_package(package: Path, destination: Path) -> None:
    archive = package.read_bytes()
    if not archive.startswith(b"!<arch>\n"):
        raise SystemExit(f"not a Debian package: {package}")
    offset = 8
    while offset < len(archive):
        header = archive[offset : offset + 60]
        if len(header) != 60 or header[58:60] != b"`\n":
            raise SystemExit(f"invalid ar member in {package}")
        name = header[:16].decode("ascii").strip().removesuffix("/")
        size = int(header[48:58].decode("ascii").strip())
        start = offset + 60
        member = archive[start : start + size]
        if name == "data.tar.xz":
            destination.mkdir(parents=True, exist_ok=True)
            with tarfile.open(fileobj=io.BytesIO(member), mode="r:xz") as payload:
                payload.extractall(destination, filter="data")
            return
        offset = start + size + (size & 1)
    raise SystemExit(f"Debian package has no data.tar.xz: {package}")


def generate_timeconst(hz: int) -> str:
    def fmul(bits: int, numerator: int, denominator: int) -> int:
        return ((1 << bits) * numerator + denominator - 1) // denominator

    def fadj(bits: int, numerator: int, denominator: int) -> int:
        denominator //= math.gcd(numerator, denominator)
        return (1 << bits) * (denominator - 1) // denominator

    def fmuls(bits: int, numerator: int, denominator: int) -> int:
        shift = 0
        while fmul(shift, numerator, denominator) < (1 << (bits - 1)):
            shift += 1
        return shift

    def conversion(prefix: str, numerator: int, denominator: int) -> list[str]:
        shift = fmuls(32, numerator, denominator)
        return [
            f"#define {prefix}_MUL32\tU64_C(0x{fmul(shift, numerator, denominator):X})",
            f"#define {prefix}_ADJ32\tU64_C(0x{fadj(shift, numerator, denominator):X})",
            f"#define {prefix}_SHR32\t{shift}",
        ]

    if hz < 2:
        raise SystemExit(f"invalid kernel HZ: {hz}")
    lines = [
        "/* Automatically generated by kernel/time/timeconst.bc */",
        f"/* Time conversion constants for HZ == {hz} */",
        "",
        "#ifndef KERNEL_TIMECONST_H",
        "#define KERNEL_TIMECONST_H",
        "",
        "#include <linux/param.h>",
        "#include <linux/types.h>",
        "",
        f"#if HZ != {hz}",
        '#error "include/generated/timeconst.h has the wrong HZ value!"',
        "#endif",
        "",
        *conversion("HZ_TO_MSEC", 1_000, hz),
        *conversion("MSEC_TO_HZ", hz, 1_000),
    ]
    millis_gcd = math.gcd(hz, 1_000)
    lines.extend(
        [
            f"#define HZ_TO_MSEC_NUM\t\t{1_000 // millis_gcd}",
            f"#define HZ_TO_MSEC_DEN\t\t{hz // millis_gcd}",
            f"#define MSEC_TO_HZ_NUM\t\t{hz // millis_gcd}",
            f"#define MSEC_TO_HZ_DEN\t\t{1_000 // millis_gcd}",
            "",
            *conversion("HZ_TO_USEC", 1_000_000, hz),
            *conversion("USEC_TO_HZ", hz, 1_000_000),
        ]
    )
    micros_gcd = math.gcd(hz, 1_000_000)
    nanos_gcd = math.gcd(hz, 1_000_000_000)
    lines.extend(
        [
            f"#define HZ_TO_USEC_NUM\t\t{1_000_000 // micros_gcd}",
            f"#define HZ_TO_USEC_DEN\t\t{hz // micros_gcd}",
            f"#define USEC_TO_HZ_NUM\t\t{hz // micros_gcd}",
            f"#define USEC_TO_HZ_DEN\t\t{1_000_000 // micros_gcd}",
            f"#define HZ_TO_NSEC_NUM\t\t{1_000_000_000 // nanos_gcd}",
            f"#define HZ_TO_NSEC_DEN\t\t{hz // nanos_gcd}",
            f"#define NSEC_TO_HZ_NUM\t\t{hz // nanos_gcd}",
            f"#define NSEC_TO_HZ_DEN\t\t{1_000_000_000 // nanos_gcd}",
            "",
            "#endif /* KERNEL_TIMECONST_H */",
            "",
        ]
    )
    return "\n".join(lines)


def apply_unified_patch(patch_path: Path, root: Path) -> None:
    lines = patch_path.read_text(encoding="utf-8", errors="surrogateescape").splitlines(
        keepends=True
    )
    index = 0
    while index < len(lines):
        if not lines[index].startswith("diff --git "):
            index += 1
            continue
        index += 1
        old_name = new_name = None
        while index < len(lines) and not lines[index].startswith("@@ "):
            if lines[index].startswith("diff --git "):
                break
            if lines[index].startswith("--- "):
                old_name = lines[index][4:].strip().split("\t", 1)[0]
            elif lines[index].startswith("+++ "):
                new_name = lines[index][4:].strip().split("\t", 1)[0]
            index += 1
        if old_name is None or new_name is None:
            continue

        source_path = None if old_name == "/dev/null" else root / old_name.removeprefix("a/")
        target_path = None if new_name == "/dev/null" else root / new_name.removeprefix("b/")
        source = [] if source_path is None else source_path.read_text(
            encoding="utf-8", errors="surrogateescape"
        ).splitlines(keepends=True)
        output = []
        cursor = 0
        while index < len(lines) and lines[index].startswith("@@ "):
            header = lines[index].split("@@", 2)[1].strip().split()
            old_range = header[0][1:].split(",", 1)
            new_range = header[1][1:].split(",", 1)
            old_start = int(old_range[0])
            old_remaining = int(old_range[1]) if len(old_range) == 2 else 1
            new_remaining = int(new_range[1]) if len(new_range) == 2 else 1
            wanted = max(old_start - 1, 0)
            if wanted < cursor:
                raise SystemExit(f"overlapping hunks in {patch_path}: {old_name}")
            output.extend(source[cursor:wanted])
            cursor = wanted
            index += 1
            while index < len(lines) and (old_remaining or new_remaining):
                line = lines[index]
                if line.startswith(("@@ ", "diff --git ")):
                    break
                if line.startswith("\\ No newline at end of file"):
                    index += 1
                    continue
                marker, content = line[:1], line[1:]
                if marker == " ":
                    if cursor >= len(source) or source[cursor] != content:
                        raise SystemExit(f"context mismatch in {patch_path}: {old_name}")
                    output.append(content)
                    cursor += 1
                    old_remaining -= 1
                    new_remaining -= 1
                elif marker == "-":
                    if cursor >= len(source) or source[cursor] != content:
                        raise SystemExit(f"removal mismatch in {patch_path}: {old_name}")
                    cursor += 1
                    old_remaining -= 1
                elif marker == "+":
                    output.append(content)
                    new_remaining -= 1
                else:
                    break
                index += 1
        output.extend(source[cursor:])
        if target_path is None:
            if source_path is not None:
                source_path.unlink()
        else:
            target_path.parent.mkdir(parents=True, exist_ok=True)
            target_path.write_text(
                "".join(output), encoding="utf-8", errors="surrogateescape"
            )


def main() -> None:
    if len(sys.argv) == 4 and sys.argv[1] == "--extract":
        archive = Path(sys.argv[2])
        destination = Path(sys.argv[3])
        with tarfile.open(archive, mode="r:xz") as source:
            source.extractall(destination, filter="data")
        return
    if len(sys.argv) == 4 and sys.argv[1] == "--apply":
        apply_unified_patch(Path(sys.argv[2]), Path(sys.argv[3]))
        return
    if len(sys.argv) == 4 and sys.argv[1] == "--extract-deb":
        extract_debian_package(Path(sys.argv[2]), Path(sys.argv[3]))
        return
    if len(sys.argv) >= 2 and sys.argv[1] == "--timeconst":
        print(generate_timeconst(int(sys.stdin.read().strip())), end="")
        return

    parser = argparse.ArgumentParser()
    parser.add_argument("vmlinux", type=Path)
    parser.add_argument("bundle", type=Path)
    parser.add_argument("metadata", type=Path)
    args = parser.parse_args()

    image = args.vmlinux.read_bytes()
    header = ELF64_HEADER.unpack_from(image)
    ident = header[0]
    if ident[:4] != b"\x7fELF" or ident[4] != 2 or ident[5] != 1:
        raise SystemExit("expected a little-endian ELF64 kernel")

    entry = header[4]
    phoff = header[5]
    phentsize = header[9]
    phnum = header[10]
    if phentsize != ELF64_PROGRAM_HEADER.size:
        raise SystemExit(f"unexpected program-header size: {phentsize}")

    segments = []
    for index in range(phnum):
        fields = ELF64_PROGRAM_HEADER.unpack_from(image, phoff + index * phentsize)
        if fields[0] == PT_LOAD:
            segments.append(fields)
    if not segments:
        raise SystemExit("kernel ELF contains no PT_LOAD segments")

    bundle = bytearray()
    load_addr = segments[0][3] & 0x0FFFFFFF
    previous_paddr = None
    previous_filesz = None
    for _, _, offset, vaddr, paddr, filesz, _, _ in segments:
        if previous_paddr is not None and previous_filesz is not None:
            padding = paddr - previous_paddr - previous_filesz
            if padding < 0:
                raise SystemExit("overlapping PT_LOAD segments")
            bundle.extend(b"\0" * padding)
        if paddr - load_addr != len(bundle):
            raise SystemExit(
                f"non-contiguous kernel layout at vaddr={vaddr:#x}, paddr={paddr:#x}"
            )
        bundle.extend(image[offset : offset + filesz])
        previous_paddr = paddr
        previous_filesz = filesz

    bundle.extend(b"\0" * (-len(bundle) % PAGE_SIZE))
    args.bundle.write_bytes(bundle)
    args.metadata.write_text(
        f"load={load_addr:#x}\nentry={entry:#x}\nsize={len(bundle)}\n",
        encoding="ascii",
    )


if __name__ == "__main__":
    main()
