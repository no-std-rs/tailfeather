#!/usr/bin/env python3
"""Regenerate bounded Unicode 17 full-fold tables from the pinned UCD fixture."""

import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "crates/tailfeather/src/unicode_normalization/CaseFolding-17.0.0.txt"
TARGET = ROOT / "crates/tailfeather/src/unicode_normalization/case_folding_tables.rs"
SHA256 = "ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183"


def main():
    data = SOURCE.read_bytes()
    if hashlib.sha256(data).hexdigest() != SHA256:
        raise SystemExit("CaseFolding-17.0.0.txt does not match the pinned SHA-256")
    mappings = {}
    for line in data.decode().splitlines():
        fields = line.split("#")[0].split(";")
        if len(fields) >= 3 and fields[1].strip() in {"C", "F"}:
            mappings[int(fields[0], 16)] = tuple(int(c, 16) for c in fields[2].split())
    assert max(map(len, mappings.values())) == 3
    singles = [(code, values[0] - code) for code, values in mappings.items() if len(values) == 1]
    ranges = []
    i = 0
    while i < len(singles):
        start, delta = singles[i]
        end, step = start, 1
        if i + 1 < len(singles):
            next_code, next_delta = singles[i + 1]
            if next_delta == delta and next_code - start in {1, 2}:
                step = next_code - start
                while i + 1 < len(singles) and singles[i + 1] == (end + step, delta):
                    i += 1
                    end += step
        ranges.append((start, end, step, delta))
        i += 1
    lines = [
        "// Generated by scripts/generate-case-folding.py; do not edit.",
        "// Unicode 17.0.0, default full case folding (C + F; excludes Turkic T).",
        "// Source: https://www.unicode.org/Public/17.0.0/ucd/CaseFolding.txt",
        f"// SHA-256: {SHA256}",
        "// Copyright 2025 Unicode, Inc. SPDX-License-Identifier: Unicode-3.0",
        "// License: crates/tailfeather/src/unicode_normalization/LICENSE-UNICODE.txt", "",
        "pub(super) const SIMPLE: &[(u32, u32, u8, i32)] = &[",
    ]
    for start, end, step, delta in ranges:
        lines.append(f"    (0x{start:04x}, 0x{end:04x}, {step}, {delta}),")
    lines.extend(["];", "", "pub(super) const FULL: &[(char, &str)] = &["])
    for code, values in mappings.items():
        if len(values) > 1:
            value = "".join(f"\\u{{{c:x}}}" for c in values)
            lines.append(f"    ('\\u{{{code:x}}}', \"{value}\"),")
    lines.extend(["];", ""])
    TARGET.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
